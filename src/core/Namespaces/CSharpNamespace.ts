/**
 * Helpers to keep C# namespace declarations in sync with the folder structure.
 *
 * This module has no VS Code or file system dependencies so it can be unit tested.
 */

export type NamespaceSyncResult =
    | { status: "updated"; content: string; previous: string; expected: string }
    | { status: "unchanged"; expected: string }
    | { status: "skipped"; reason: NamespaceSkipReason };

export type NamespaceSkipReason = "generated" | "no-namespace" | "multiple-namespaces";

type NamespaceDeclaration = { name: string; start: number; end: number };

const GENERATED_HEADER_LENGTH = 2048;

/**
 * Converts a name into a valid C# namespace, keeping dots as separators.
 * Invalid characters become "_" and segments that start with a digit get a "_" prefix,
 * the same rules Visual Studio applies to folder names.
 */
export function toNamespace(name: string): string {
    return name
        .split(".")
        .map(segment => segment.trim())
        .filter(segment => segment.length > 0)
        .map(toNamespaceSegment)
        .join(".");
}

function toNamespaceSegment(segment: string): string {
    // macOS file systems can return names in decomposed form (NFD), e.g. "Ação" as "Ac\u0327a\u0303o":
    // normalize to the composed form first, and keep combining marks, which C# allows in identifiers
    let result = segment.normalize("NFC").replace(/[^\p{L}\p{M}\p{N}_]/gu, "_");
    if (/^\p{N}/u.test(result)) {
        result = "_" + result;
    }

    return result;
}

/**
 * Returns the root namespace of a project: the `RootNamespace` MSBuild property when it is
 * a literal value, otherwise the project name.
 */
export function getRootNamespace(rootNamespaceProperty: string | undefined, projectName: string): string {
    const value = (rootNamespaceProperty ?? "").trim();
    if (value && !value.includes("$(")) {
        return toNamespace(value);
    }

    return toNamespace(projectName);
}

/**
 * Returns the namespace a file should have: the root namespace plus the folders between
 * the project directory and the file.
 *
 * Example: root "Acme.Api" and folders ["Features", "Orders"] -> "Acme.Api.Features.Orders".
 */
export function getExpectedNamespace(rootNamespace: string, folderSegments: string[]): string {
    const parts = [ rootNamespace, ...folderSegments.map(toNamespace) ]
        .filter(part => part.length > 0);

    return parts.join(".");
}

/**
 * Updates the namespace declaration of a C# file so it matches `expectedNamespace`.
 * Works with file-scoped (`namespace X;`) and block-scoped (`namespace X { }`) declarations.
 *
 * Files are skipped, and left untouched, when they are auto-generated, declare no namespace
 * or declare more than one namespace.
 */
export function syncNamespaceDeclaration(content: string, expectedNamespace: string): NamespaceSyncResult {
    if (isGenerated(content)) {
        return { status: "skipped", reason: "generated" };
    }

    // fast path: most files without the keyword (e.g. top-level statements) need no parsing
    if (!content.includes("namespace")) {
        return { status: "skipped", reason: "no-namespace" };
    }

    const declarations = findNamespaceDeclarations(content);
    if (declarations.length === 0) {
        return { status: "skipped", reason: "no-namespace" };
    }

    if (declarations.length > 1) {
        return { status: "skipped", reason: "multiple-namespaces" };
    }

    const [ declaration ] = declarations;
    if (declaration.name === expectedNamespace) {
        return { status: "unchanged", expected: expectedNamespace };
    }

    const updated = content.substring(0, declaration.start) + expectedNamespace + content.substring(declaration.end);
    return { status: "updated", content: updated, previous: declaration.name, expected: expectedNamespace };
}

function isGenerated(content: string): boolean {
    return /<auto-generated/i.test(content.substring(0, GENERATED_HEADER_LENGTH));
}

/**
 * Finds `namespace` declarations outside comments, strings and character literals.
 */
const NAMESPACE_DECLARATION = /(?<![\p{L}\p{M}\p{N}_@.])namespace\s+([\p{L}_@][\p{L}\p{M}\p{N}_@]*(?:\s*\.\s*[\p{L}_@][\p{L}\p{M}\p{N}_@]*)*)\s*[;{]/gu;

export function findNamespaceDeclarations(content: string): NamespaceDeclaration[] {
    const code = maskCommentsAndStrings(content);
    const pattern = NAMESPACE_DECLARATION;
    pattern.lastIndex = 0;
    const result: NamespaceDeclaration[] = [];

    let match: RegExpExecArray | null;
    while ((match = pattern.exec(code)) !== null) {
        const nameStart = match.index + match[0].indexOf(match[1], "namespace".length);
        const rawName = content.substring(nameStart, nameStart + match[1].length);
        result.push({
            name: rawName.replace(/\s+/g, ""),
            start: nameStart,
            end: nameStart + match[1].length
        });
    }

    return result;
}

/**
 * Replaces comments, strings and character literals with spaces (keeping line breaks),
 * so that positions in the masked text match positions in the original text.
 */
export function maskCommentsAndStrings(content: string): string {
    const ranges = findCommentAndStringRanges(content);
    if (ranges.length === 0) {
        return content;
    }

    const parts: string[] = [];
    let previous = 0;
    for (let k = 0; k < ranges.length; k += 2) {
        const from = ranges[k];
        const to = ranges[k + 1];
        parts.push(content.substring(previous, from), blank(content.substring(from, to)));
        previous = to;
    }
    parts.push(content.substring(previous));

    return parts.join("");
}

function blank(text: string): string {
    // most comments and strings are single-line: repeat() is much faster than a regex replace
    if (text.indexOf("\n") < 0 && text.indexOf("\r") < 0) {
        return " ".repeat(text.length);
    }

    return text.replace(/[^\r\n]/g, " ");
}

// characters that can start a comment, a string or a char literal
const LITERAL_START = /[\/"'$@]/g;

/**
 * Returns the [start, end) offsets of comments, strings and char literals as a flat list:
 * [start1, end1, start2, end2, ...]. Jumps straight to the next character that can start one
 * instead of visiting every character.
 */
function findCommentAndStringRanges(content: string): number[] {
    const ranges: number[] = [];
    const length = content.length;
    const starts = LITERAL_START;
    let i = 0;

    while (i < length) {
        starts.lastIndex = i;
        const found = starts.exec(content);
        if (!found) {
            break;
        }

        i = found.index;
        const c = content[i];
        const next = content[i + 1];
        let end = -1;

        if (c === "/" && next === "/") {
            // line comment
            end = indexOrLength(content, "\n", i);
        } else if (c === "/" && next === "*") {
            // block comment
            const close = content.indexOf("*/", i + 2);
            end = close < 0 ? length : close + 2;
        } else if (c === "'") {
            // character literal
            end = skipCharLiteral(content, i);
        } else if (c !== "/") {
            // string literals, with optional $ and @ prefixes in any order
            const prefix = readStringPrefix(content, i);
            if (prefix !== null) {
                const quoteStart = i + prefix.length;
                end = prefix.includes("@")
                    ? skipVerbatimString(content, quoteStart)
                    : skipQuotedString(content, quoteStart);
            }
        }

        if (end > i) {
            ranges.push(i, end);
            i = end;
        } else {
            i++;
        }
    }

    return ranges;
}

function indexOrLength(content: string, search: string, from: number): number {
    const index = content.indexOf(search, from);
    return index < 0 ? content.length : index;
}

function readStringPrefix(content: string, index: number): string | null {
    let prefix = "";
    let i = index;
    while (i < content.length && (content[i] === "$" || content[i] === "@") && prefix.length < 4) {
        prefix += content[i];
        i++;
    }

    if (content[i] !== '"') {
        return null;
    }

    return prefix;
}

function skipQuotedString(content: string, quoteStart: number): number {
    // raw string literal: three or more quotes
    let quotes = 0;
    while (content[quoteStart + quotes] === '"') {
        quotes++;
    }

    if (quotes >= 3) {
        const delimiter = '"'.repeat(quotes);
        const close = content.indexOf(delimiter, quoteStart + quotes);
        return close < 0 ? content.length : close + quotes;
    }

    if (quotes === 2) {
        // empty string ""
        return quoteStart + 2;
    }

    let i = quoteStart + 1;
    while (i < content.length) {
        const c = content[i];
        if (c === "\\") {
            i += 2;
            continue;
        }

        if (c === '"' || c === "\n") {
            return i + 1;
        }

        i++;
    }

    return content.length;
}

function skipVerbatimString(content: string, quoteStart: number): number {
    let i = quoteStart + 1;
    while (i < content.length) {
        if (content[i] === '"') {
            if (content[i + 1] === '"') {
                i += 2;
                continue;
            }

            return i + 1;
        }

        i++;
    }

    return content.length;
}

function skipCharLiteral(content: string, start: number): number {
    let i = start + 1;
    while (i < content.length && i < start + 12) {
        const c = content[i];
        if (c === "\\") {
            i += 2;
            continue;
        }

        if (c === "'" || c === "\n") {
            return i + 1;
        }

        i++;
    }

    return start + 1;
}
